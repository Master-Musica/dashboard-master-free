== Installation ==

1. Upload the plugin files to the `/wp-content/plugins/dashboard-master` directory, or install the plugin through the WordPress plugins screen directly.
2. Activate the plugin through the 'Plugins' screen in WordPress.
3. Navigate to **Dashboard Master** in the main admin menu to configure your AdBlocker words and custom widgets.

