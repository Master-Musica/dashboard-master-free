Take control of your WordPress dashboard. Block aggressive admin notices and create custom welcome blocks for your network.

== Description ==

Dashboard Master is the ultimate tool to clean up your WordPress admin area and communicate effectively with your users or clients. 

Tired of aggressive marketing banners, "upgrade now" notices, and cluttered dashboards from other plugins? The **Smart AdBlocker** engine scans your dashboard and completely hides notices containing specific keywords, keeping your workspace clean and professional.

Furthermore, Dashboard Master allows you to completely replace the default WordPress dashboard widgets with your own custom content using a visual editor.

= Free Version Features =
* **Smart AdBlocker:** Hide intrusive admin notices by defining a list of forbidden keywords.
* **Global Network Block:** Create 1 fixed block that will appear across your entire network (perfect for Super Admins).
* **Local Blocks:** Create up to 3 custom dashboard widgets specific to the current site.
* **YouTube Fix:** Automatically applies `strict-origin-when-cross-origin` to prevent embed errors.

